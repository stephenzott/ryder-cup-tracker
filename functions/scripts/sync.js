// Copies the website's scoring math into this folder, so the Cloud
// Function and the website use the SAME code and can never disagree
// about who won a hole.
//
//   public/js/scoring.js        ->  functions/scoring.js
//   public/js/rounds-config.js  ->  functions/rounds-config.js
//
// WHY COPY instead of importing straight from public/: when Firebase
// deploys a function it uploads ONLY the functions/ folder, so code
// outside it doesn't exist on the server. Copying at deploy time (this
// runs automatically before `firebase deploy --only functions`, see
// "predeploy" in firebase.json) keeps one true source in public/js/
// while still shipping a copy with the function. The copies are listed
// in .gitignore so nobody edits them by mistake: edit public/js/ only.
//
// Run by hand with:  npm run sync   (npm test runs it first, too)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// This file's own folder (functions/scripts), then up to the project.
const here = dirname(fileURLToPath(import.meta.url));
const functionsDir = join(here, "..");
const publicJs = join(functionsDir, "..", "public", "js");

const FILES = ["scoring.js", "rounds-config.js"];

for (const name of FILES) {
  const source = readFileSync(join(publicJs, name), "utf8");

  // Safety check: a copied file must not import anything, because its
  // imports would point at website files that don't exist in functions/.
  // If someone adds an import to scoring.js later, stop loudly here
  // rather than deploy a function that crashes on start.
  if (/^\s*import\s/m.test(source)) {
    console.error(`sync: ${name} now imports another file, so it can't be copied into functions/. Stopping.`);
    process.exit(1);
  }

  writeFileSync(join(functionsDir, name), source);
  console.log(`sync: copied public/js/${name} -> functions/${name}`);
}

// The trip year. It lives in public/js/match-ui.js (CURRENT_YEAR), which
// can't be copied whole (it imports browser code), so just that one line
// is read and written to functions/trip-year.js. The function puts the
// year in its dedupe ids (notificationLog/2027_round2_match2_hole7), so
// changing CURRENT_YEAR for next year's trip is all it takes for alerts
// to start fresh.
const matchUi = readFileSync(join(publicJs, "match-ui.js"), "utf8");
const yearMatch = matchUi.match(/export const CURRENT_YEAR = (\d{4});/);
if (!yearMatch) {
  console.error("sync: couldn't find `export const CURRENT_YEAR = <year>;` in public/js/match-ui.js. Stopping.");
  process.exit(1);
}
writeFileSync(
  join(functionsDir, "trip-year.js"),
  `// Generated by scripts/sync.js from public/js/match-ui.js. Don't edit.\nexport const CURRENT_YEAR = ${yearMatch[1]};\n`
);
console.log(`sync: trip year ${yearMatch[1]} -> functions/trip-year.js`);
